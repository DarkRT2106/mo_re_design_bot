# ФОРМИРОВАНИЕ И ОТПРАВКА ЗАКАЗА
# =========================================================

async def finish_order(message: types.Message):

    user_id = message.from_user.id

    order = user_orders[user_id]

    service_name = order["service_name"]
    category = order["category"]

    questions = order["questions"]
    answers = order["answers"]

    username = (
        f"@{message.from_user.username}"
        if message.from_user.username
        else "нет username"
    )

    full_name = message.from_user.full_name

    # -----------------------------------------------------
    # Формируем список ответов
    # -----------------------------------------------------

    answers_text = ""

    for index in range(len(questions)):

        answers_text += (
            f"\n<b>{index + 1}. "
            f"{questions[index]}</b>\n"
            f"{answers[index]}\n"
        )

    # -----------------------------------------------------
    # Заявка менеджеру
    # -----------------------------------------------------

    admin_text = (
        "🔔 <b>НОВАЯ ЗАЯВКА</b>\n\n"

        f"👤 <b>Клиент:</b> {full_name}\n"
        f"🔗 <b>Username:</b> {username}\n"
        f"🆔 <b>Telegram ID:</b> "
        f"<code>{user_id}</code>\n\n"

        f"📂 <b>Категория:</b> {category}\n"
        f"📌 <b>Услуга:</b> {service_name}\n\n"

        "━━━━━━━━━━━━━━━━━━\n"
        "📋 <b>ОТВЕТЫ КЛИЕНТА</b>\n"
        "━━━━━━━━━━━━━━━━━━\n"
        f"{answers_text}"
    )

    try:

        await bot.send_message(
            ADMIN_ID,
            admin_text,
            parse_mode="HTML"
        )

        # -------------------------------------------------
        # Сообщение клиенту
        # -------------------------------------------------

        await message.answer(
            "✅ <b>Спасибо!</b>\n\n"
            "Вы ответили на все вопросы.\n\n"
            "Ваша заявка уже отправлена менеджеру. "
            "Он ознакомится с деталями и свяжется "
            "с вами для дальнейшего обсуждения заказа.",
            parse_mode="HTML"
        )

        # -------------------------------------------------
        # Очищаем заказ
        # -------------------------------------------------

        del user_orders[user_id]

    except Exception as error:

        print(
            "Ошибка отправки заявки менеджеру:",
            error
        )

        await message.answer(
            "❌ Произошла ошибка при отправке заявки менеджеру.\n\n"
            "Пожалуйста, попробуйте ещё раз немного позже."
        )


