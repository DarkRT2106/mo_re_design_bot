@dp.message_handler(content_types=types.ContentTypes.TEXT)
async def receive_answer(message: types.Message):

    user_id = message.from_user.id

    # -----------------------------------------------------
    # Нет активного заказа
    # -----------------------------------------------------

    if user_id not in user_orders:

        await message.answer(
            "Сначала выберите интересующую вас услугу 👇",
            reply_markup=main_menu_keyboard()
        )

        return

    order = user_orders[user_id]

    questions = order["questions"]
    current_question = order["current_question"]

    # -----------------------------------------------------
    # Сохраняем ответ
    # -----------------------------------------------------

    order["answers"].append(message.text)

    # Переходим к следующему вопросу
    order["current_question"] += 1

    current_question = order["current_question"]

    # -----------------------------------------------------
    # Есть ещё вопросы
    # -----------------------------------------------------

    if current_question < len(questions):

        await message.answer(
            f"❓ <b>Вопрос {current_question + 1} "
            f"из {len(questions)}</b>\n\n"
            f"{questions[current_question]}",
            parse_mode="HTML"
        )

        return

    # -----------------------------------------------------
    # Все вопросы закончились
    # -----------------------------------------------------

    await finish_order(message)


